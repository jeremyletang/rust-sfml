//! Selection of the audio playback device
//!
//! The playback device is the output that sounds are played through.
//! This module lists the available devices, selects one, and reports changes
//! to the state of the playback device.

use {
    crate::{IntoSfResult as _, SfResult, cpp::FBox, ffi::audio as ffi},
    std::{
        ffi::{CString, c_int, c_void},
        ptr,
        sync::{Mutex, PoisonError},
    },
};

/// Notification about a change to the state of the playback device
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Notification {
    /// The playback device has been started
    DeviceStarted,
    /// The playback device has been stopped
    DeviceStopped,
    /// The playback device has been rerouted (generated on platforms that support automatic stream routing)
    DeviceRerouted,
    /// The playback device interruption has begun (generated on Apple mobile platforms)
    DeviceInterruptionBegan,
    /// The playback device interruption has ended (generated on Apple mobile platforms)
    DeviceInterruptionEnded,
    /// The playback device has been unlocked (generated by Emscripten/WebAudio)
    DeviceUnlocked,
}

impl Notification {
    fn from_raw(raw: c_int) -> Option<Self> {
        Some(match raw {
            0 => Self::DeviceStarted,
            1 => Self::DeviceStopped,
            2 => Self::DeviceRerouted,
            3 => Self::DeviceInterruptionBegan,
            4 => Self::DeviceInterruptionEnded,
            5 => Self::DeviceUnlocked,
            _ => return None,
        })
    }
}

type NotificationCallback = dyn Fn(Notification) + Send;

/// The notification callback that SFML currently calls.
///
/// The closure is double boxed so that a thin pointer to it can be passed to SFML as user data.
static NOTIFICATION_CALLBACK: Mutex<Option<Box<Box<NotificationCallback>>>> = Mutex::new(None);

unsafe extern "C" fn notification_trampoline(notification: c_int, user_data: *mut c_void) {
    let callback = unsafe { &*user_data.cast::<Box<NotificationCallback>>() };
    if let Some(notification) = Notification::from_raw(notification) {
        callback(notification);
    }
}

/// Get the names of all available audio playback devices
///
/// If the operating system reports multiple devices with the same name, a number is appended
/// to the names of the subsequent devices so that every name is unique.
/// The default device, if there is one, is placed first.
///
/// # Panics
///
/// Panics on allocation failure.
#[must_use]
pub fn available_devices() -> Vec<String> {
    unsafe { FBox::new(ffi::sfPlaybackDevice_getAvailableDevices()) }
        .expect("Failed to create sfStdStringVector")
        .iter()
        .map(|device| device.to_rust_string_lossy())
        .collect()
}

/// Get the name of the default audio playback device
///
/// Returns `None` if there is no default device.
/// The default device can change when a device is plugged in or unplugged.
#[must_use]
pub fn default_device() -> Option<String> {
    unsafe { FBox::new(ffi::sfPlaybackDevice_getDefaultDevice()) }
        .map(|device| device.to_rust_string_lossy())
}

/// Get the name of the current audio playback device
///
/// Returns `None` if there is no current device.
#[must_use]
pub fn device() -> Option<String> {
    unsafe { FBox::new(ffi::sfPlaybackDevice_getDevice()) }
        .map(|device| device.to_rust_string_lossy())
}

/// Set the audio playback device
///
/// `name` must be one of the names returned by [`available_devices`].
/// It can be called on the fly, while sounds are playing. Sounds keep playing on the new device.
pub fn set_device(name: &str) -> SfResult<()> {
    let name = CString::new(name)?;
    unsafe { ffi::sfPlaybackDevice_setDevice(name.as_ptr()) }.into_sf_result()
}

/// Set the audio playback device to the default device
///
/// When the backend supports it, the device follows the system default automatically,
/// rerouting the audio when the default device changes.
/// It can be called on the fly, while sounds are playing.
pub fn set_device_to_default() -> SfResult<()> {
    unsafe { ffi::sfPlaybackDevice_setDeviceToDefault() }.into_sf_result()
}

/// Set the audio playback device to the null device
///
/// Audio sent to the null device is discarded by the backend.
/// Sounds keep playing without being output on a physical device.
/// It can be called on the fly, while sounds are playing.
pub fn set_device_to_null() -> SfResult<()> {
    unsafe { ffi::sfPlaybackDevice_setDeviceToNull() }.into_sf_result()
}

/// Check whether the current audio playback device is the default device
///
/// Returns `false` if there is no current device.
#[must_use]
pub fn is_default_device() -> bool {
    unsafe { ffi::sfPlaybackDevice_isDefaultDevice() }
}

/// Get the sample rate of the current audio playback device
///
/// Returns `None` if there is no current device.
#[must_use]
pub fn device_sample_rate() -> Option<u32> {
    let mut sample_rate = 0;
    let found = unsafe { ffi::sfPlaybackDevice_getDeviceSampleRate(&mut sample_rate) };
    found.then_some(sample_rate)
}

/// Set the callback that is called when the state of the playback device changes
///
/// Passing `None` removes the callback.
///
/// SFML calls the callback from an internal thread, so it must not block for long.
/// It must not panic, since unwinding across the C boundary aborts the process.
///
/// Do not change the playback device or call `set_notification_callback` from within the callback.
/// Doing so deadlocks. Instead, store the notification and react to it from another thread.
pub fn set_notification_callback<F>(callback: Option<F>)
where
    F: Fn(Notification) + Send + 'static,
{
    let mut stored = NOTIFICATION_CALLBACK
        .lock()
        .unwrap_or_else(PoisonError::into_inner);
    let new = callback.map(|callback| {
        let closure: Box<NotificationCallback> = Box::new(callback);
        Box::new(closure)
    });
    let (callback_fn, user_data): (ffi::sfPlaybackDeviceNotificationCallback, *mut c_void) =
        match &new {
            Some(boxed) => (
                Some(notification_trampoline),
                ptr::from_ref(boxed.as_ref()).cast_mut().cast::<c_void>(),
            ),
            None => (None, ptr::null_mut()),
        };
    unsafe { ffi::sfPlaybackDevice_setNotificationCallback(callback_fn, user_data) };
    // SFML calls the callback while holding the same lock the setter takes,
    // so the previous closure can't be running once the setter has returned.
    *stored = new;
}

#[cfg_attr(not(feature = "ci-headless"), test)]
#[cfg_attr(feature = "ci-headless", expect(dead_code))]
fn test_default_device_is_available() {
    if let Some(default) = default_device() {
        assert!(available_devices().iter().any(|device| device == &default));
    }
}

#[cfg_attr(not(feature = "ci-headless"), test)]
#[cfg_attr(feature = "ci-headless", expect(dead_code))]
fn test_available_device_names_are_unique() {
    let devices = available_devices();
    for (i, device) in devices.iter().enumerate() {
        assert!(
            devices.iter().skip(i + 1).all(|other| other != device),
            "duplicate device name: {device}"
        );
    }
}
